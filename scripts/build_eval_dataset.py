def assertion(
    row_index: int,
    field: str,
    expected: str | int | float | bool | None,
    operator: str = "eq",
) -> dict[str, Any]:
    return {
        "row_index": row_index,
        "field": field,
        "operator": operator,
        "expected": expected,
    }


def case(
    case_id: str,
    category: str,
    difficulty: str,
    language: str,
    question: str,
    tables: list[str],
    *,
    sql: str | None = None,
    row_count: int | None = None,
    assertions: list[dict[str, Any]] | None = None,
    terms: list[str] | None = None,
    tolerance: float = 0.0,
    behavior: str = "allow",
) -> dict[str, Any]:
    return {
        "id": case_id,
        "category": category,
        "difficulty": difficulty,
        "language": language,
        "question": question,
        "relevant_tables": tables,
        "reference_sql": sql,
        "expected_row_count": row_count,
        "assertions": assertions or [],
        "required_answer_terms": terms or [],
        "numeric_tolerance": tolerance,
        "expected_security_behavior": behavior,
    }


